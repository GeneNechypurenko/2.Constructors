#include <iostream>
#include <cstring>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                 Список ініціалізації та Делегування конструкторів
==========================================================================================================================================

  Насправді в тілі конструктора поля не ініціалізуються: спочатку створюються поля об'єкта (вони містять «сміття»), і лише потім виконується
  тіло конструктора, де полям ПРИСВОЮЮТЬСЯ значення. Щоб поля ініціалізувалися одразу при створенні, використовують СПИСОК ІНІЦІАЛІЗАЦІЇ.

  СПИСОК ІНІЦІАЛІЗАЦІЇ — це спосіб задати полям початкові значення в момент їх створення, ще до виконання тіла конструктора.
  Поля ініціалізуються в порядку їх оголошення в класі, тому список пишуть у тому самому порядку.

  ДЕЛЕГУВАННЯ КОНСТРУКТОРІВ — виклик одного конструктора класу з іншого конструктора ТОГО САМОГО класу. Викликликається в СПИСКУ ІНІЦІАЛІЗАЦІЇ.
  - Головний конструктор виконує всю роботу, інші лише передають йому значення.
  - Спершу повністю виконується головний конструктор, потім — тіло делегуючого.
  - Виклик іншого конструктора — ЄДИНИЙ елемент списку ініціалізації: поруч не можна ініціалізувати інші поля.

  Переваги делегування конструкторів
  - Немає дублювання коду: логіка створення об'єкта — в одному місці.
  - Простіше змінювати: нову перевірку чи дію додають лише в головний конструктор.
  - Менше помилок: неможливо «забути» ініціалізувати поле в одному з конструкторів.
  - Конструктори стають короткими й зрозумілими.
*/

class Student
{
private:
    char* name;
    int age;
    double averageGrade;

public:
    // ГОЛОВНИЙ конструктор: поля ініціалізуються в списку, а не присвоюються в тілі
    Student(const char* newName, int newAge, double newGrade) : name(nullptr), age(newAge), averageGrade(newGrade)
    {
        // У тілі — лише дії: виділення пам'яті під ім'я
        setName(newName);
    }

    // ДЕЛЕГУЮЧИЙ конструктор: середній бал невідомий — передаємо 0 головному
    Student(const char* newName, int newAge) : Student(newName, newAge, 0) {}

    // ДЕЛЕГУЮЧИЙ конструктор за замовчуванням
    Student() : Student("Невідомий", 16, 0) {}

    ~Student()
    {
        delete[] name;
    }

    void setName(const char* newName)
    {
        delete[] name;
        int length = strlen(newName) + 1;
        name = new char[length];
        strcpy_s(name, length, newName);
    }

    void print()
    {
        cout << name << ", вік: " << age << ", середній бал: " << averageGrade << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "Студент a:" << endl;
    Student a("Олена", 20, 10.5);    // одразу головний конструктор

    cout << "Студент b:" << endl;
    Student b("Ігор", 22);            // делегуючий → головний

    cout << "Студент c:" << endl;
    Student c;                        // за замовчуванням → головний

    cout << endl;
    a.print();
    b.print();
    c.print();

    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - Головним зазвичай роблять конструктор з найбільшою кількістю параметрів.
  - Зверніть увагу на порядок повідомлень: тіло головного конструктора виконується ПЕРШИМ, тіло делегуючого — після нього.
  - Делегування має бути ЄДИНИМ елементом списку ініціалізації:  Student() : Student("Невідомий", 16, 0), age(18) - ПОМИЛКА компіляції
  - Конструктори не можуть делегувати по колу (A викликає B, а B викликає A).
  - Є два варіанти списка ініціалізації (як і створення об'єктів): пряма ініціалізація - name(newName), уніфікована ініціалізація - name{newName}.
  Обидві робочі, при тому що уніфікована важжається безпечнішою (захищає від неявного звужуючого приведення типів), серед розробників все одно
  більш популярна пряма ініціалізація через круглі дужки.

  ПРАКТИКА

  1. Клас Box (коробка) — список ініціалізації.
     - private-поля: int length, int width, int height.
     - Конструктор Box(newLength, newWidth, newHeight) — усі три поля ініціалізуються у СПИСКУ ІНІЦІАЛІЗАЦІЇ, тіло конструктора порожнє.
     - Інспектор getVolume() — повертає length * width * height.
     - Метод print() — виводить «Коробка ДxШxВ, об'єм: ...».
     - У main: створіть дві коробки з різними розмірами і виведіть їх.

  2. Клас Pet (домашній улюбленець) — список ініціалізації і делегування.
     - private-поля: char* name, int age.
     - Метод setName(newName) — як setName у Student.
     - Головний конструктор Pet(newName, newAge): у списку ініціалізації name(nullptr), age(newAge), у тілі — виклик setName(newName).
     - Делегуючий конструктор Pet(newName) — передає головному вік 0.
     - Делегуючий конструктор Pet() — передає головному ім'я «Безіменний» і вік 0.
     - Кожен делегуючий конструктор виводить своє повідомлення в тілі.
     - Деструктор — звільняє пам'ять, виділену під ім'я.
     - Метод print() — виводить ім'я та вік.
     - У main: створіть по одному улюбленцю кожним конструктором, виведіть усіх і подивіться на порядок повідомлень конструкторів.
*/
